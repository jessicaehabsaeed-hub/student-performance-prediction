import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

data = {
    "study_hours": [2, 3, 5, 4, 6, 7, 1, 8, 5, 3,
                    6, 7, 2, 4, 8, 9, 3, 5, 6, 7],

    "attendance": [65, 70, 85, 80, 90, 95, 60, 98, 88, 72,
                    92, 94, 68, 78, 97, 99, 75, 86, 91, 93],

    "previous_score": [55, 60, 72, 68, 80, 85, 50, 90, 76, 63,
                       82, 87, 58, 70, 92, 95, 65, 74, 84, 88],

    "sleep_hours": [5, 6, 7, 6, 8, 7, 5, 8, 7, 6,
                    7, 8, 5, 6, 8, 7, 6, 7, 8, 7],

    "assignments_completed": [60, 65, 80, 75, 90, 95, 50, 100, 85, 70,
                              92, 96, 55, 78, 98, 100, 72, 84, 93, 95],

    "final_score": [58, 63, 75, 70, 83, 88, 52, 94, 79, 66,
                    85, 90, 60, 73, 96, 98, 68, 78, 87, 91]
}

df = pd.DataFrame(data)

df.head()

